import assert from 'node:assert/strict';
import {readFileSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,...(process.env.HARVEY_BROWSER_EXECUTABLE?{executablePath:process.env.HARVEY_BROWSER_EXECUTABLE}:{})});
try{
  const page=await browser.newPage({viewport:{width:1440,height:950}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><html></html>'}));
  await page.goto('http://harvey.test/harvey');
  await page.setContent('<body style="font:18px system-ui;background:#f7f8fa;padding:35px"><h1>Workflow review</h1><p>Connected to the fixture workspace</p><hr><h2>Daily report</h2><p>Review pending tasks · Prepare summary · Verify results</p></body>');
  const image='data:image/jpeg;base64,'+(await page.screenshot({type:'jpeg'})).toString('base64');
  await page.setContent(readFileSync('public/harvey.html','utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,''));
  await page.addStyleTag({content:readFileSync('public/harvey-work.css','utf8')});
  await page.addStyleTag({content:readFileSync('public/harvey-computer.css','utf8')});
  await page.addScriptTag({content:readFileSync('public/harvey-computer.js','utf8')});
  await page.addScriptTag({content:readFileSync('public/harvey-work.js','utf8')});
  await page.evaluate(image=>{
    window.pending=[];window.requests=[];window.slow=false;
    window.fetch=async url=>{
      requests.push(url);const chatId=url.split('/').at(-2);
      const data={chatId,state:'ready',phase:'running',action:'browser_snapshot',frame:{image,capturedAt:new Date().toISOString(),url:'https://fixture.test/'+chatId,title:'Workflow review'}};
      if(window.slow)return new Promise(resolve=>pending.push(()=>resolve({ok:true,json:async()=>data})));
      return {ok:true,json:async()=>data};
    };
    window.hooks={state:{conversationId:'first',mode:'work',view:'chat',conversations:[]},apiUrl:p=>p,api:async()=>({ok:true,data:{projects:[],schedules:[],runs:[]}}),toast(){}};
    HarveyComputer.init(hooks);HarveyWork.init(hooks);
  },image);
  await page.locator('#computerImage:not([hidden])').waitFor();
  assert((await page.locator('#computerPage').textContent()).endsWith('/first'));
  const panel=await page.locator('#computerPanel').boundingBox(),main=await page.locator('#main').boundingBox();
  assert(main.x+main.width<=panel.x+1,'Desktop panel must not cover chat');
  await page.locator('#computerExpand').click();assert.equal(await page.locator('#computerExpand').getAttribute('aria-pressed'),'true');
  await page.locator('#computerExpand').click();
  mkdirSync('artifacts/computer-panel',{recursive:true});
  await page.screenshot({path:'artifacts/computer-panel/desktop.png'});
  await page.evaluate(()=>{window.slow=true;});await page.locator('#computerRefresh').click();
  await page.waitForFunction(()=>pending.length===1);
  await page.evaluate(()=>{hooks.state.conversationId='second';HarveyComputer.sync();});
  assert(await page.locator('#computerImage').isHidden());
  await page.waitForFunction(()=>pending.length===2);
  await page.evaluate(()=>pending.shift()());assert(await page.locator('#computerImage').isHidden());
  await page.evaluate(()=>pending.shift()());await page.locator('#computerImage:not([hidden])').waitFor();
  assert((await page.locator('#computerPage').textContent()).endsWith('/second'));
  console.log('ok desktop layout, expand, per-chat clearing and stale-response isolation');
  await page.locator('#taskPanelOpen').click();assert(await page.locator('#computerPanel').isHidden());
  await page.locator('#computerPanelOpen').click();assert(await page.locator('#taskPanel').isHidden());
  await page.locator('#computerPanelClose').click();
  const count=await page.evaluate(()=>requests.length);await page.waitForTimeout(4500);assert.equal(await page.evaluate(()=>requests.length),count);
  await page.evaluate(()=>{hooks.state.conversationId=null;HarveyComputer.sync();});
  assert(await page.locator('#computerImage').isHidden());assert.equal(await page.locator('#computerStatus').textContent(),'Ready when you are');
  console.log('ok Tasks and Computer panels are mutually exclusive; hidden panels stop polling; new chat clears old frame');
  await page.setViewportSize({width:390,height:844});
  const mobile=await page.locator('#computerPanel').boundingBox();assert(mobile.width<=390);assert(mobile.x>=0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  assert(await page.evaluate(()=>!!document.elementFromPoint(35,35)?.closest('#computerPanel')),'Mobile preview must be above the navigation drawer');
  await page.screenshot({path:'artifacts/computer-panel/mobile.png'});
  await page.keyboard.press('Escape');assert(await page.locator('#computerPanel').isHidden());
  assert.deepEqual(errors,[]);console.log('ok mobile sizing, keyboard close, no script errors');
}finally{await browser.close();}
