import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,mkdirSync,readdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
const {recoverMarcoCrm}=createRequire(import.meta.url)('../dist/src/core/crmRecovery.js');
const root=mkdtempSync(join(tmpdir(),'crm-restore-')),target=join(root,'marco');
const data={idCounter:5,leadsById:{'4':{id:'4',name:'Fixture',phone:'2025550141',notes:'Retain notes',custom:{status:'active'}}},leadKeyToId:{'test:four':'4'},conversationsByLeadId:{'4':{leadId:'4',messages:[{text:'Fixture message'}]}},commandTasks:[{id:'not-a-crm-record'}]};
const original=JSON.stringify(data);writeFileSync(join(root,'db.json'),original);
recoverMarcoCrm(root,target);
const restored=JSON.parse(readFileSync(join(target,'db.json')));
for(const key of ['idCounter','leadsById','leadKeyToId','conversationsByLeadId'])assert.deepEqual(restored[key],data[key]);
assert.deepEqual(restored.commandTasks,[]);
assert.equal(readFileSync(join(root,'db.json'),'utf8'),original);
const backups=readdirSync(join(root,'crm-recovery-backups'));assert.equal(backups.length,1);assert.equal(readFileSync(join(root,'crm-recovery-backups',backups[0]),'utf8'),original);
restored.leadsById['4'].phone='2025550999';writeFileSync(join(target,'db.json'),JSON.stringify(restored));
recoverMarcoCrm(root,target);assert.equal(JSON.parse(readFileSync(join(target,'db.json'))).leadsById['4'].phone,'2025550999');
const other=join(root,'existing');mkdirSync(other);writeFileSync(join(other,'local-dashboard-db.json'),'{"leadsById":{}}');recoverMarcoCrm(root,other);assert.equal(readdirSync(other).length,1);
console.log('CRM recovery passed: exact lead/phone/notes/conversation preservation, retained backup, idempotence, existing-store protection.');
