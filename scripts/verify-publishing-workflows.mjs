import assert from 'node:assert/strict';
import {plannerTime,planPatch,selectedTargets,requireFutureSchedule} from '../dist/src/core/smartPosterPlanning.js';
import {hasDmPhoneCapture} from '../dist/src/core/dmMetrics.js';
import {mapPost} from '../dist/src/integrations/zernio/index.js';
assert.equal(plannerTime('2026-11-09','10:30','America/Chicago'),'2026-11-09T16:30:00.000Z');
assert.equal(plannerTime('2026-07-09','10:30','America/Chicago'),'2026-07-09T15:30:00.000Z');
assert.throws(()=>plannerTime('2027-03-14','02:30','America/Chicago'),/does not exist/);
assert.throws(()=>plannerTime('2026-02-30','10:30','America/Chicago'));
const accounts=[{id:'a',platform:'instagram',active:true},{id:'b',platform:'instagram',active:true},{id:'off',platform:'tiktok',active:false}];
assert.deepEqual(selectedTargets(['b','b'],accounts),[{accountId:'b',platform:'instagram'}]);
assert.throws(()=>selectedTargets([],accounts),/at least one/);
assert.throws(()=>selectedTargets(['off'],accounts),/disconnected/);
assert.throws(()=>selectedTargets(['unknown'],accounts),/unavailable/);
const post={id:'p',status:'inbox',title:'Home',caption:'Caption',accountIds:[],scheduledFor:null,timezone:'America/Chicago'};
const plan=planPatch(post,{localDate:'2026-11-09',localTime:'10:30',accountIds:['b']});
assert.equal(plan.status,'ready');assert.equal(plan.targetDate,'2026-11-09');assert.equal(post.status,'inbox');
assert.equal(planPatch(plan,{scheduledFor:null,accountIds:[]}).status,'draft');
assert.throws(()=>planPatch({...post,status:'published'},{title:'No'}),/Published/);
assert.throws(()=>requireFutureSchedule(plan,Date.parse('2026-11-10')),/future/);
assert.equal(hasDmPhoneCapture({phone:'123'},{messages:[]}),false);
assert.equal(hasDmPhoneCapture({phone:'123'},{messages:[{role:'user',text:'Hello'}]}),true);
assert.equal(hasDmPhoneCapture({phone:'  '},{messages:[{role:'user',text:'Hello'}]}),false);
const row=mapPost({postId:'external-1',content:'Actual description',platformPostUrl:'https://example.com/video',analytics:{views:100}});
assert.equal(row.id,'external-1');assert.equal(row.caption,'Actual description');assert.equal(row.url,'https://example.com/video');
assert.equal(mapPost({content:' ',description:'Fallback description'}).caption,'Fallback description');
console.log('Publishing workflow checks passed: exact targets, timezone/DST, immutable plans, future dates, DM captures, external captions.');
